"""Convert flyer art into colored ASCII data for the site's canvas flyers.

usage: flyer2ascii.py MAIN.webp OUT.js [--cols 120] [--alt ALT.webp] [--preview DIR]

The main image becomes the flyer; the optional alt image (same grid) is what the
flyer glitches into for a split second. Crops/masks below are tuned per flyer.
"""
import argparse, colorsys, json
from PIL import Image, ImageDraw, ImageFont
import pyfiglet

CHAR_ASPECT = 0.6  # monospace cell width / height at line-height 1
RAMP = " .,:;-~=+*ox%#@"
B64 = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_"
SMOKE, GAIN, GAMMA = 0.25, 1.35, 0.9

# Halloween flyers: main = calm skull (lettering blacked out, rendered as real text),
# alt = the scarier glitched face, cropped tighter so it lunges at the viewer.
MAIN_CROP, MAIN_MASKS = (0, 255, 1198, 1300), [(0, 925, 275, 1130)]
ALT_CROP, ALT_MASKS = (330, 390, 1200, 1149), []


def is_red(p):
    r, g, b = p
    return r > 150 and r > 1.9 * g and r > 1.9 * b


def convert(path, crop, masks, cols, rows=None, smoke=SMOKE):
    im = Image.open(path).convert("RGB")
    d = ImageDraw.Draw(im)
    for m in masks:
        d.rectangle(m, fill=(0, 0, 0))
    im = im.crop(crop)
    w, h = im.size
    rows = rows or round(cols * h / w * CHAR_ASPECT)
    small = im.resize((cols, rows), Image.BOX)

    cells, boosted = [], Image.new("RGB", (cols, rows))
    for y in range(rows):
        for x in range(cols):
            r, g, b = small.getpixel((x, y))
            hh, ss, vv = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
            # Saturated subjects (green skull, red eyes, blue hood) carry the image;
            # grey smoke is pushed back into the dark.
            v = max(0.0, min(1.0, (vv - 0.08) / 0.6)) * (smoke + (1 - smoke) * min(1, ss * 1.6))
            v = min(1.0, v * GAIN) ** GAMMA
            rr, gg, bb = colorsys.hsv_to_rgb(hh, min(1, ss * 1.25), min(1, 0.45 + 0.6 * vv))
            boosted.putpixel((x, y), (int(rr * 255), int(gg * 255), int(bb * 255)))
            # A white-hot core counts as eye when it sits inside a red glow.
            core = vv > 0.8 and r >= g and r >= b and sum(
                is_red(small.getpixel((xx, yy)))
                for xx in range(max(0, x - 3), min(cols, x + 4))
                for yy in range(max(0, y - 2), min(rows, y + 3))
            ) >= 8
            if core:
                v = 1.0
            cells.append((v, is_red((r, g, b)) or core))

    pal_img = boosted.quantize(colors=64, method=Image.Quantize.MEDIANCUT)
    pal = pal_img.getpalette()[: 64 * 3]
    palette = ["#%02x%02x%02x" % tuple(pal[i * 3 : i * 3 + 3]) for i in range(64)]

    chars, colors, eyes = [], [], []
    for y in range(rows):
        crow, colrow = "", ""
        for x in range(cols):
            v, eye = cells[y * cols + x]
            c = RAMP[min(len(RAMP) - 1, int(v * len(RAMP)))]
            if eye and c == " ":
                c = "o"
            crow += c
            colrow += B64[pal_img.getpixel((x, y))]
            if eye:
                eyes.append(y * cols + x)
        chars.append(crow)
        colors.append(colrow)
    return {"palette": palette, "chars": chars, "colors": colors, "eyes": eyes}, rows


def preview(art, cols, rows, path):
    font = ImageFont.truetype("/System/Library/Fonts/Menlo.ttc", 14)
    cw, ch = 8.43, 14
    img = Image.new("RGB", (int(cols * cw) + 10, rows * ch + 10), (5, 8, 5))
    d = ImageDraw.Draw(img)
    for y in range(rows):
        for x in range(cols):
            c = art["chars"][y][x]
            if c != " ":
                d.text((5 + x * cw, 5 + y * ch), c, font=font, fill=art["palette"][B64.index(art["colors"][y][x])])
    img.save(path)


def fig(text):
    return [l.rstrip() for l in pyfiglet.figlet_format(text, font="ansi_shadow").splitlines() if l.strip()]


ap = argparse.ArgumentParser()
ap.add_argument("main")
ap.add_argument("out")
ap.add_argument("--cols", type=int, default=120)
ap.add_argument("--alt")
ap.add_argument("--preview")
a = ap.parse_args()

main, rows = convert(a.main, MAIN_CROP, MAIN_MASKS, a.cols)
data = {"cols": a.cols, "rows": rows, **main, "title": [fig("HALLOWEEN"), fig("PARTY")]}
if a.preview:
    preview(main, a.cols, rows, f"{a.preview}/main.png")
if a.alt:
    alt, _ = convert(a.alt, ALT_CROP, ALT_MASKS, a.cols, rows, smoke=0.55)
    data["alt"] = alt
    if a.preview:
        preview(alt, a.cols, rows, f"{a.preview}/alt.png")

with open(a.out, "w") as f:
    f.write("// Generated by tools/flyer2ascii.py. Do not hand-edit.\n")
    f.write("window.FLYERS = window.FLYERS || {};\nwindow.FLYERS.halloween = ")
    json.dump(data, f, separators=(",", ":"))
    f.write(";\n")
print(a.cols, rows, "eyes:", len(main["eyes"]), "alt:", bool(a.alt))
